/** 各语言缺失 key 的回退语言 */
const FALLBACK: Record<Locale, Locale> = {
  "zh-CN": "en",
  en: "en",
  "zh-TW": "en",
  ja: "en",
  ko: "en",
  fr: "en",
  de: "en",
  es: "en",
  pt: "en",
  it: "en",
  nl: "en",
  ru: "en",
  tr: "en",
  ar: "en",
  th: "en",
  vi: "en",
  id: "en",
  hi: "en",
};

function buildDictionaries(): Record<Locale, Dict> {
  const out = {} as Record<Locale, Dict>;
  for (const { code } of LOCALES) {
    if (code === "zh-CN") {
      out[code] = zhCN;
    } else if (code === "en") {
      out[code] = en;
    } else {
      const base = FALLBACK[code] === "zh-CN" ? zhCN : en;
      out[code] = { ...base, ...PARTIAL[code] };
    }
  }
  return out;
}

export const DICTIONARIES: Record<Locale, Dict> = buildDictionaries();

/** 纯函数翻译（无 React 依赖，可在任意处调用） */
export function translate(
  locale: Locale,
  key: string,
  vars?: Record<string, string | number>
): string {
  const dict = DICTIONARIES[locale] ?? DICTIONARIES.en;
  let text = dict[key] ?? DICTIONARIES.en[key] ?? DICTIONARIES["zh-CN"][key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.split(`{${k}}`).join(String(v));
    }
  }
  return text;
}
